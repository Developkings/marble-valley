import { Course, type CourseData, type CourseOp, type Dir, type Kind } from './course';

// Closed circuits for racing. The first piece is the start line and they all set off heading N.
// Each is laid out up to a last leg heading S, level with the start and to the right of it,
// and joined up from there on two curves: west along the bottom, then north up to the line.
function circuit(id: string, name: string, width: number, ops: CourseOp[]): CourseData {
  const head: CourseOp[] = [{ op: 'run', dir: 'N', len: 3, width, kind: 'finish' }, ...ops];
  const radius = width / 2 + 8;
  const round: CourseOp[] = [...head, { op: 'bend', to: 'W', radius, width }];
  const along = new Course({ version: 1, id, name, ops: [...round, { op: 'bend', to: 'N', radius, width }] }).end;
  const straight: CourseOp[] = along.x > 0 ? [{ op: 'run', dir: 'W', len: along.x, width }, { op: 'items', along: -8, across: [-3, 0, 3].map((a) => (a * width) / 10) }] : [];
  return {
    version: 1,
    id,
    name,
    kind: 'circuit',
    ops: [...round, ...straight, { op: 'bend', to: 'N', radius, width }, { op: 'run', dir: 'N', len: along.z, width }],
  };
}

const row = (along: number, width: number): CourseOp => ({ op: 'items', along, across: [-3, 0, 3].map((a) => Math.round((a * width) / 10)) });
const run = (dir: Dir, len: number, width: number, kind?: Kind, rise?: number): CourseOp => ({ op: 'run', dir, len, width, kind, rise });
const bend = (to: Dir, radius: number, width: number, kind?: Kind, rail?: boolean): CourseOp => ({ op: 'bend', to, radius, width, kind, rail });
const snake = (len: number, width: number, amp: number, waves = 1, kind?: Kind): CourseOp => ({ op: 'wave', len, width, amp, waves, kind });
const roller = (len: number, width: number, hump: number, humps: number): CourseOp => ({ op: 'wave', len, width, hump, humps, kind: 'fast' });

