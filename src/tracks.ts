import { Course, type CourseData, type CourseOp } from './course';
import { boost, climb, flat, jump, speed, ice, zigzag } from './pieces';

// Closed circuits for racing. The first piece is the start line and they all set off heading N.
// Each is laid out up to a last leg heading S, level with the start and to the right of it, and
// joined up from there: west along the bottom, then north up to the line.
function circuit(id: string, name: string, width: number, ops: CourseOp[]): CourseData {
  const head: CourseOp[] = [{ op: 'run', dir: 'N', len: 3, width, kind: 'finish' }, ...ops];
  const end = new Course({ version: 1, id, name, ops: head }).end;
  return {
    version: 1,
    id,
    name,
    kind: 'circuit',
    ops: [
      ...head,
      { op: 'run', dir: 'W', len: end.x - width, width },
      { op: 'items', along: -8, across: [-3, 0, 3].map((a) => (a * width) / 10) },
      { op: 'run', dir: 'N', len: end.z - 1, width },
    ],
  };
}

const row = (along: number, width: number): CourseOp => ({ op: 'items', along, across: [-3, 0, 3].map((a) => Math.round((a * width) / 10)) });

